def _entries(text):
    return [tuple(e.split()) for e in text.replace("\n", "").split("|") if e.strip()]


def _norm_entry(tokens):
    return tuple(un.process_token(norm(t)) for t in tokens)


def build_gazetteer():
    """Returns dict: normalised-token-tuple -> type, and raw counts per type."""
    gaz, raw = {}, {}
    for typ, txt in [("MISC", MISC), ("LOC", LOC), ("ORG", ORG), ("PER", PER_INTL), ("PER", PER_PK)]:
        ents = _entries(txt)
        raw.setdefault(typ, 0)
        raw[typ] += len(ents)
        for e in ents:
            gaz[_norm_entry(e)] = typ      # later (more specific) types overwrite MISC etc.
    return gaz, raw


