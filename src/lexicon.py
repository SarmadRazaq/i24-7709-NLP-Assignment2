def norm(w: str) -> str:
    w = un.remove_diacritics(un.normalize_unicode(w.strip()))
    return w


def norm_forms(w: str):
    w = norm(w)
    return {w, un.process_token(w)} if w else set()


def _set(text):
    return [w for w in text.split() if w]


